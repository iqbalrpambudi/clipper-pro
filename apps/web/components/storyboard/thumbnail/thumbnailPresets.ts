export function convertLegacyOverlayToLayers(
  legacyOverlay?: any,
  defaultTitle?: string
): ThumbnailTextLayer[] {
  if (legacyOverlay?.layers && Array.isArray(legacyOverlay.layers) && legacyOverlay.layers.length > 0) {
    return legacyOverlay.layers;
  }

  const line1Text = legacyOverlay?.line1 || defaultTitle || "MISTERI BESAR";
  const line2Text = legacyOverlay?.line2 || "TERNYATA BEGINI?!";
  const font = legacyOverlay?.font_family || "Anton";
  const size = legacyOverlay?.font_size ? Math.max(36, Math.min(76, legacyOverlay.font_size)) : 56;
  const rot = legacyOverlay?.rotation ?? -2;
  const spread = legacyOverlay?.outline_spread ?? 2.0;

  return [
    {
      id: "layer_default_1",
      text: line1Text.toUpperCase(),
      x: 70,
      y: 90,
      fontSize: size,
      fontFamily: font,
      fill: legacyOverlay?.color1 || "#FFFFFF",
      rotation: rot,
      scaleX: 1,
      scaleY: 1,
      strokeEnabled: legacyOverlay?.outline_enabled ?? true,
      stroke: legacyOverlay?.outline_color || "#000000",
      strokeWidth: Math.round(spread * 2.5),
      bgEnabled: false,
      bgFill: "#E50914",
      bgPaddingX: 16,
      bgPaddingY: 8,
      bgCornerRadius: 8,
      bgOpacity: 1,
      shadowEnabled: legacyOverlay?.blur_enabled ?? true,
      shadowColor: "rgba(0,0,0,0.85)",
      shadowBlur: legacyOverlay?.outline_blur ? Math.min(8, legacyOverlay.outline_blur) : 4,
      shadowOffsetX: 3,
      shadowOffsetY: 4,
      shadowOpacity: 0.8,
    },
    {
      id: "layer_default_2",
      text: line2Text.toUpperCase(),
      x: 70,
      y: 180,
      fontSize: size,
      fontFamily: font,
      fill: legacyOverlay?.color2 || "#FFE600",
      rotation: rot,
      scaleX: 1,
      scaleY: 1,
      strokeEnabled: legacyOverlay?.outline_enabled ?? true,
      stroke: legacyOverlay?.outline_color || "#000000",
      strokeWidth: Math.round(spread * 2.5),
      bgEnabled: false,
      bgFill: "#E50914",
      bgPaddingX: 16,
      bgPaddingY: 8,
      bgCornerRadius: 8,
      bgOpacity: 1,
      shadowEnabled: legacyOverlay?.blur_enabled ?? true,
      shadowColor: "rgba(0,0,0,0.85)",
      shadowBlur: legacyOverlay?.outline_blur ? Math.min(8, legacyOverlay.outline_blur) : 4,
      shadowOffsetX: 3,
      shadowOffsetY: 4,
      shadowOpacity: 0.8,
    },
  ];
}
